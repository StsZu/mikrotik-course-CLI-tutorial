  function viewLesson(id, stepStr) {
    var e = byId[id];
    if (!e) return viewNotFound('Урок не знайдено', 'Можливо, файл цього модуля ще не готовий.');
    if (!isUnlocked(e)) return lockedLessonView(e);
    var L = e.lesson, n = L.steps.length;
    if (!n) {
      mount(backLink(moduleHref(e.module), moduleLabel(e.module)) +
        emptyState('book', L.title, 'У цьому уроці ще немає кроків.', L.quiz.length ? '<a class="btn btn-filled" href="' + quizHref(e) + '">' + ic('quiz') + '<span>До quiz</span></a>' : ''), L.title);
      return qs('h1');
    }
    var p = lp(L.id);
    var free = p.stepsDone || p.passed;
    var gatedType = function (k) {
      var step = L.steps[k], t = step && step.type;
      return t === 'check' || t === 'terminal';
    };
    var solved = function (k) {
      var st = session[L.id + ':' + k];
      return !!st && (st.choice != null || st.solved === true);
    };
    var maxAllowed = free ? n - 1 : Math.min(n - 1, (gatedType(p.step) && !solved(p.step)) ? p.step : p.step + 1);
    var i = clamp((parseInt(stepStr, 10) || 1) - 1, 0, n - 1);
    if (i > maxAllowed) {
      i = maxAllowed;
      try { history.replaceState(null, '', lessonHref(e, i + 1)); } catch (err) { /* file:// in some browsers */ }
    }
    p.step = Math.max(p.step, i);
    P.last = L.id;
    save();

    var s = L.steps[i];
    var isLast = i === n - 1;
    var ctx = {
      key: L.id + ':' + i,
      lesson: L,
      unlock: function () {
        var b = qs('#step-next');
        if (b) b.disabled = false;
        var h = qs('#step-hint');
        if (h) h.textContent = 'Enter — далі';
      },
      nextButton: function () { return qs('#step-next'); }
    };
    var r = renderStep(s, ctx);
    var needsAnswer = !free && !r.ungated && gatedType(i) && i === p.step && !solved(i);
    var nextLabel = isLast ? (L.quiz.length ? 'До quiz' : 'Завершити урок') : 'Далі';
    var hint = needsAnswer ? (s.type === 'check' ? 'Обери відповідь, щоб продовжити' : 'Виконай команду, щоб продовжити') : 'Enter — далі';
    var html =
      '<div class="player-head">' + backLink(moduleHref(e.module), moduleLabel(e.module) + ' · ' + e.module.title) +
      '<h1 class="title-large">' + esc(L.title) + '</h1>' +
      linear(i + 1, n, 'Прогрес уроку') +
      '<div class="player-meta"><span class="label-large muted">Крок ' + (i + 1) + ' з ' + n + '</span>' +
      (L.minutes ? chip(L.minutes + ' хв', '', 'timer') : '') + '</div></div>' +
      '<article class="step-card step-' + esc(s.type || 'unknown') + (r.cls ? ' ' + r.cls : '') + '" aria-labelledby="step-title">' + r.html + '</article>' +
      '<div class="player-actions">' +
      (i > 0 ? '<a class="btn btn-outlined" href="' + lessonHref(e, i) + '">' + ic('arrow_back') + '<span>Назад</span></a>'
        : '<a class="btn btn-outlined" href="' + moduleHref(e.module) + '">' + ic('arrow_back') + '<span>Модуль</span></a>') +
      '<span class="hint" id="step-hint" aria-live="polite">' + esc(hint) + '</span>' +
      '<button class="btn btn-filled" type="button" id="step-next"' + (needsAnswer ? ' disabled' : '') + '><span>' + nextLabel + '</span>' + ic(isLast ? 'quiz' : 'arrow_forward') + '</button>' +
      '</div>';
    mount(html, L.title);
    var root = qs('.step-card');
    if (r.bind) {
      try { r.bind(root); } catch (err) { if (window.console) console.warn('Step bind failed', s, err); ctx.unlock(); }
    }

    var goNext = function () {
      var b = qs('#step-next');
      if (!b) return;
      if (b.disabled) {
        snackbar(s.type === 'check' ? 'Спершу обери відповідь' : 'Спершу виконай завдання або покажи відповідь після 2 спроб');
        return;
      }
      if (!isLast) {
        p.step = Math.max(p.step, i + 1);
        save();
        location.hash = lessonHref(e, i + 2);
        return;
      }
      p.stepsDone = true;
      if (L.quiz.length) { save(); location.hash = quizHref(e); return; }
      var was = p.passed;
      p.passed = true;
      save();
      if (!was) snackbar('Урок пройдено!');
      var nx = lessons[e.index + 1];
      location.hash = nx ? lessonHref(nx, 1) : moduleHref(e.module);
    };
    qs('#step-next').addEventListener('click', goNext);
    keys.next = goNext;
    return qs('#step-title');
  }
