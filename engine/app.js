  // Full-string comparison only: trims, collapses spaces, unifies quotes; lowercases for case-insensitive shells.
  function normCmd(s, ci) {
    s = String(s || '').replace(/[“”„«»]/g, '"').replace(/[‘’ʼ]/g, "'").replace(/\s+/g, ' ').trim();
    return (ci == null ? CASE_INSENSITIVE : ci) ? s.toLowerCase() : s;
  }

  function copyText(text) {
    var done = function () { snackbar('Команду скопійовано'); };
    var fallback = function () {
      try {
        var ta = document.createElement('textarea');
        ta.value = text; ta.setAttribute('readonly', ''); ta.style.position = 'fixed'; ta.style.opacity = '0';
        document.body.appendChild(ta); ta.select();
        var ok = document.execCommand('copy');
        document.body.removeChild(ta);
        if (ok) done(); else snackbar('Не вдалося скопіювати — виділи команду вручну');
      } catch (e) { snackbar('Не вдалося скопіювати — виділи команду вручну'); }
    };
    if (navigator.clipboard && window.isSecureContext) navigator.clipboard.writeText(text).then(done, fallback);
    else fallback();
  }


