  function resultComment(pct) {
    if (pct >= 90) return 'Відмінний результат! Ти впевнено розумієш цю тему.';
    if (pct >= 70) return 'Добрий результат. Основне засвоєно — кілька деталей варто ще раз переглянути.';
    if (pct >= 50) return 'Непогано, але варто ще попрактикуватися: переглянь кроки уроку й спробуй ще раз.';
    return 'Рекомендуємо повторити матеріал і пройти quiz ще раз — у тебе все вийде.';
  }

  // opts: { questions, onFinish(score, pct) -> {passed, best, attempts, statusText, actions(html)} }
  function runQuiz(host, opts) {
    var SRC = opts.questions, N = SRC.length, Q = SRC.map(shuffleQuestion);
    var state = { k: 0, score: 0, chosen: null };

    function renderQuestion() {
      var q = Q[state.k];
      state.chosen = null;
      var last = state.k === N - 1;
      host.innerHTML =
        '<div class="quiz-top"><span class="label-large">Питання ' + (state.k + 1) + ' з ' + N + '</span>' +
        '<span class="label-large muted">Правильних: <span id="q-score">' + state.score + '</span></span></div>' +
        linear(state.k, N, 'Прогрес quiz') +
        '<h2 class="title-large" id="q-title" tabindex="-1">' + esc(q.title || ('Питання ' + (state.k + 1))) + '</h2>' +
        '<p class="question">' + rt(q.question) + '</p>' +
        optionsHtml(q.options.map(String)) +
        '<div class="feedback-slot" aria-live="polite"></div>' +
        '<div class="quiz-foot"><button class="btn btn-filled btn-lg" type="button" id="q-next" disabled><span>' +
        (last ? 'Показати результат' : 'Наступне питання') + '</span>' + ic(last ? 'emoji_events' : 'arrow_forward') + '</button></div>';
      qsa('.option', host).forEach(function (b) {
        b.addEventListener('click', function () { choose(Number(b.getAttribute('data-opt'))); });
      });
      qs('#q-next', host).addEventListener('click', next);
      keys.choose = function (i) { return choose(i); };
      keys.next = function () { var b = qs('#q-next', host); if (b && !b.disabled) next(); };
    }

    function choose(i) {
      var q = Q[state.k];
      if (state.chosen != null || i < 0 || i >= q.options.length) return false;
      state.chosen = i;
      var ok = i === q.correct;
      if (ok) state.score++;
      applyAnswer(host, q.correct, i);
      qs('.feedback-slot', host).innerHTML = feedbackHtml(ok, q.feedback, String(q.options[q.correct]));
      qs('#q-score', host).textContent = state.score;
      var bar = qs('.linear-progress', host);
      bar.setAttribute('aria-valuenow', state.k + 1);
      qs('span', bar).style.width = ((state.k + 1) / N * 100).toFixed(1) + '%';
      var nb = qs('#q-next', host);
      nb.disabled = false;
      focusEl(nb);
      return true;
    }

    function next() {
      if (state.chosen == null) return;
      if (state.k < N - 1) {
        state.k++;
        renderQuestion();
        focusEl(qs('#q-title', host));
        if (host.scrollIntoView) host.scrollIntoView({ block: 'start', behavior: reducedMotion ? 'auto' : 'smooth' });
      } else {
        showResult();
      }
    }

    function showResult() {
      keys.choose = null;
      var pct = Math.round(state.score / N * 100);
      var res = opts.onFinish(state.score, pct);
      host.innerHTML = '<div class="result">' +
        circular(pct, { large: true, done: res.passed, label: 'Результат ' + pct + '%' }) +
        '<h2 class="headline-small" id="q-title" tabindex="-1">' + state.score + ' з ' + N + ' правильних</h2>' +
        '<span class="chip ' + (res.passed ? 'chip-success' : 'chip-error') + ' result-status">' + ic(res.passed ? 'check_circle' : 'info') + '<span>' +
        esc(res.statusText) + '</span></span>' +
        '<p class="body-large">' + esc(resultComment(pct)) + '</p>' +
        '<p class="body-medium muted">Найкращий результат: ' + res.best + '% · спроб: ' + res.attempts + '</p>' +
        '<div class="actions">' + res.actions + '</div></div>';
      var retry = qs('[data-retry]', host);
      if (retry) retry.addEventListener('click', function () {
        state.k = 0; state.score = 0;
        Q = SRC.map(shuffleQuestion);
        renderQuestion();
        focusEl(qs('#q-title', host));
      });
      var primary = qs('.result .btn-filled', host);
      keys.next = primary ? function () { primary.click(); } : null;
      focusEl(qs('#q-title', host));
    }

    renderQuestion();
  }

