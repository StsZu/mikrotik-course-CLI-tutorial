  /* ---------- glossary ---------- */
  function collectGlossary() {
    var map = {};
    var list = [];
    lessons.forEach(function (e) {
      e.lesson.glossary.forEach(function (g) {
        if (!g || !g.term) return;
        var key = String(g.term).trim().toLocaleLowerCase('uk');
        if (!map[key]) { map[key] = { term: String(g.term).trim(), def: str(g.def), refs: [] }; list.push(map[key]); }
        if (!map[key].refs.some(function (r) { return r.entry === e; })) map[key].refs.push({ entry: e });
      });
    });
    return list.sort(function (a, b) { return a.term.localeCompare(b.term, 'uk', { sensitivity: 'base' }); });
  }

